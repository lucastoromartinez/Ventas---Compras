def normalizar_cuit(cuit) -> str:
    """Deja solo dígitos, para comparar CUITs sin importar guiones/espacios."""
    return "".join(ch for ch in str(cuit) if ch.isdigit())


def buscar_por_cuit(cuit) -> str | None:
    """Devuelve el nombre del proveedor para un CUIT, o None si no está cargado."""
    return PADRON_PROVEEDORES.get(normalizar_cuit(cuit))


def buscar_por_nombre(nombre: str, score_minimo: int = 85):
    """
    Busca el proveedor cuyo nombre más se parezca a `nombre` (fuzzy matching).
    Devuelve (cuit, nombre) del mejor candidato, o None si ninguno supera score_minimo.
    """
    if not nombre or not PADRON_PROVEEDORES:
        return None

    match = process.extractOne(
        nombre, PADRON_PROVEEDORES, scorer=fuzz.token_sort_ratio, processor=utils.default_process
    )
    if match is None:
        return None

    _, score, cuit = match
    if score < score_minimo:
        return None

    return cuit, PADRON_PROVEEDORES[cuit]
